"""Step 6a: English report targets for every record -> artifacts/reports_en.parquet"""
import sys
import time

import pandas as pd
import torch

from claims.config import load_config
from claims.data import load_metadata
from claims.report_text import detect_language, normalise, translate_reports


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    cfg = load_config()
    meta = load_metadata(cfg)
    raw = [normalise(t) for t in meta["report"].astype(str)]
    langs = [detect_language(t) for t in raw]
    t = time.time()
    en = translate_reports(raw, langs, device="cuda" if torch.cuda.is_available() else "cpu")
    df = pd.DataFrame({"ecg_id": meta.index, "lang": langs, "report_raw": raw, "report_en": en,
                       "autogenerated": meta["initial_autogenerated_report"].values,
                       "validated_by_human": meta["validated_by_human"].values}).set_index("ecg_id")
    df.to_parquet(cfg.path("artifacts") / "reports_en.parquet")
    print(f"translated in {time.time()-t:.0f}s; languages: {df.lang.value_counts().to_dict()}")
    for lang in ("de", "sv", "en"):
        print(f"--- {lang}")
        for _, r in df[df.lang == lang].sample(6, random_state=3).iterrows():
            print("  RAW:", r.report_raw[:160])
            print("  EN :", r.report_en[:160])


if __name__ == "__main__":
    main()
