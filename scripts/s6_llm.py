"""Step 6: LLM report generation.

  python scripts/s6_llm.py prepare    # clean targets, build train/val pairs, validate the concept extractor
  python scripts/s6_llm.py train      # LoRA fine-tune (train folds, out-of-fold evidence)
  python scripts/s6_llm.py generate   # template / zero-shot / fine-tuned reports for the test fold
"""
import argparse
import json
import sys
import time

import numpy as np
import pandas as pd

from claims.claims_builder import evidence_to_text
from claims.config import load_config
from claims.grounding import SUPPORTED_BY, evidence_index, extract_concepts
from claims.report_text import clean_target
from claims.utils import keep_awake

# extractor concept -> cardiologist label codes that should co-occur (for extractor validation)
CONCEPT_TO_LABELS = {
    "SR": {"SR"}, "AFIB": {"AFIB"}, "AFLT": {"AFLT"}, "STACH": {"STACH"}, "SBRAD": {"SBRAD"}, "SARRH": {"SARRH"},
    "PACE": {"PACE"}, "NORM": {"NORM"}, "CLBBB": {"CLBBB"}, "CRBBB": {"CRBBB"}, "IRBBB": {"IRBBB"},
    "LAFB/LPFB": {"LAFB", "LPFB"}, "_AVB": {"1AVB", "2AVB", "3AVB"}, "LVH": {"LVH"}, "IMI": {"IMI", "ILMI", "IPMI", "IPLMI"},
    "AMI": {"ASMI", "AMI", "ALMI"}, "WPW": {"WPW"}, "LAO/LAE": {"LAO/LAE"},
}


def load_evidence(cfg, split):
    with open(cfg.path("artifacts") / "evidence" / f"evidence_{split}.jsonl", encoding="utf-8") as f:
        return {e["ecg_id"]: e for e in map(json.loads, f)}


def supported(concepts: set, ev: dict) -> bool:
    idx = evidence_index(ev)
    return all(any(idx.get(e) for e in SUPPORTED_BY.get(c, {c})) for c in concepts)


def prepare(cfg, out):
    rep = pd.read_parquet(cfg.path("artifacts") / "reports_en.parquet")
    labels = pd.read_pickle(cfg.path("cache") / "labels.pkl")
    rep["target"] = rep.report_en.map(clean_target)
    stats = {"no_interpretation": int(rep.target.isna().sum())}

    # ---- concept extractor validation: extracted from the cardiologist's own report vs their own labels
    rows = []
    sub = rep[rep.target.notna()]
    lab_sets = {e: set(labels.at[e, "diagnostic"]) | set(labels.at[e, "rhythm"]) for e in sub.index}
    ext = {e: extract_concepts(t) for e, t in sub.target.items()}
    for c, labs in CONCEPT_TO_LABELS.items():
        y = np.array([bool(lab_sets[e] & labs) for e in sub.index])
        p = np.array([c in ext[e] for e in sub.index])
        if y.sum() >= 20:
            rows.append({"concept": c, "n_label": int(y.sum()), "recall": p[y].mean(), "precision": y[p].mean() if p.any() else np.nan})
    ext_val = pd.DataFrame(rows)
    print("concept extractor vs cardiologist labels (same report):")
    print(ext_val.round(3).to_string(index=False))
    stats["extractor_macro_recall"] = float(ext_val.recall.mean())
    stats["extractor_macro_precision"] = float(ext_val.precision.mean())

    # ---- training pairs: train folds use out-of-fold evidence; val fold for monitoring
    for split in ("train", "val", "test"):
        evs = load_evidence(cfg, split)
        pairs, n_faithful = [], 0
        for eid, ev in evs.items():
            tgt = rep.at[eid, "target"]
            if tgt is None:
                continue
            cs = extract_concepts(tgt)
            ok = supported(cs, ev)
            n_faithful += ok
            pairs.append({"ecg_id": eid, "evidence": evidence_to_text(ev), "target": tgt, "faithful": bool(ok),
                          "autogenerated": bool(rep.at[eid, "autogenerated"]), "lang": rep.at[eid, "lang"]})
        with open(out / f"pairs_{split}.jsonl", "w", encoding="utf-8") as f:
            for p in pairs:
                f.write(json.dumps(p) + "\n")
        stats[split] = {"pairs": len(pairs), "faithful": n_faithful, "faithful_frac": n_faithful / len(pairs)}
        print(split, stats[split])
    json.dump(stats, open(out / "prepare_stats.json", "w"), indent=1)


def read_pairs(out, split):
    with open(out / f"pairs_{split}.jsonl", encoding="utf-8") as f:
        return [json.loads(l) for l in f]


def train(cfg, out):
    from claims.llm import finetune_lora
    tr = [p for p in read_pairs(out, "train") if p["faithful"]]
    va = [p for p in read_pairs(out, "val") if p["faithful"]]
    logf = open(out / "train.log", "a", encoding="utf-8")

    def log(s):
        print(s, flush=True)
        logf.write(s + "\n")
        logf.flush()

    log(f"training on {len(tr)} faithful train pairs, monitoring {len(va)} val pairs")
    finetune_lora(cfg, [(p["evidence"], p["target"]) for p in tr], [(p["evidence"], p["target"]) for p in va],
                  str(out / "lora"), log=log)


def generate(cfg, out, limit=None):
    import torch
    from claims.llm import generate as gen, load_llm, template_report
    evs = load_evidence(cfg, "test")
    pairs = {p["ecg_id"]: p for p in read_pairs(out, "test")}
    ids = sorted(evs)[:limit] if limit else sorted(evs)
    texts = [evidence_to_text(evs[i]) for i in ids]
    res = {i: {"ecg_id": i, "reference": pairs[i]["target"] if i in pairs else None,
               "template": template_report(evs[i])} for i in ids}
    for name, adapter in (("zero_shot", None), ("finetuned", str(out / "lora"))):
        t = time.time()
        tok, model = load_llm(cfg.llm.base_model, adapter)
        outs = gen(tok, model, texts, bs=16)
        for i, o in zip(ids, outs):
            res[i][name] = o
        print(f"{name}: {len(ids)} reports in {time.time()-t:.0f}s", flush=True)
        del model
        torch.cuda.empty_cache()
    with open(out / "reports_test.jsonl", "w", encoding="utf-8") as f:
        for i in ids:
            f.write(json.dumps(res[i]) + "\n")


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    ap = argparse.ArgumentParser()
    ap.add_argument("mode", choices=["prepare", "train", "generate"])
    ap.add_argument("--limit", type=int, default=None)
    a = ap.parse_args()
    keep_awake()
    cfg = load_config()
    out = cfg.path("artifacts") / "llm"
    out.mkdir(parents=True, exist_ok=True)
    {"prepare": lambda: prepare(cfg, out), "train": lambda: train(cfg, out),
     "generate": lambda: generate(cfg, out, a.limit)}[a.mode]()


if __name__ == "__main__":
    main()
